import pandas as pd
from pulp import LpProblem, LpVariable, LpMinimize, lpSum

# Load your dataset
file_path = '/content/drive/MyDrive/Colab Notebooks/medical_resource_allocation_binary_dataset.csv'
data = pd.read_csv(file_path)

# Create synthetic costs and waiting times
data['Cost'] = data['Duration_of_Stay'] * 10
data['WaitingTime'] = 100 - data['Resource_Utilization_Efficiency'] * 100

# Get unique patient and resource IDs
patients = data['Patient_ID'].unique()
resources = data['Resource_ID'].unique()

# Initialize the optimization problem
prob = LpProblem("Healthcare_Resource_Allocation", LpMinimize)

# Define decision variables
x = {(i, j): LpVariable(f"x_{i}_{j}", cat='Binary') for i in patients for j in resources}

# Objective function
prob += lpSum([
    0.7 * data.loc[(data['Patient_ID'] == i) & (data['Resource_ID'] == j), 'WaitingTime'].values[0] * x[i, j] +
    0.3 * data.loc[(data['Patient_ID'] == i) & (data['Resource_ID'] == j), 'Cost'].values[0] * x[i, j]
    for i in patients for j in resources if not data.loc[(data['Patient_ID'] == i) & (data['Resource_ID'] == j)].empty
])

# Add constraints: Each patient gets one resource
for i in patients:
    prob += lpSum([x[i, j] for j in resources if (i, j) in x]) == 1

# Add constraints: Each resource is assigned to at most one patient
for j in resources:
    prob += lpSum([x[i, j] for i in patients if (i, j) in x]) <= 1

# Solve the problem
prob.solve()

# Collect and save results
allocation = []
for i in patients:
    for j in resources:
        if (i, j) in x and x[i, j].varValue == 1:
            allocation.append((i, j))

allocation_df = pd.DataFrame(allocation, columns=["Patient_ID", "Resource_ID"])
allocation_df.to_csv('allocation_results.csv', index=False)

